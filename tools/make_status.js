#!/usr/bin/env node
// Generates registry/STATUS.md and the progress block in README.md.
// Use --check to fail (instead of writing) when they are out of date.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const STATUS = ['idea', 'spec', 'logic', 'playable', 'polished', 'shipped'];
const registry = JSON.parse(fs.readFileSync(path.join(ROOT, 'registry', 'mechanics.json'), 'utf8'));
const ms = registry.mechanics;

const rank = (m) => STATUS.indexOf(m.status);
const total = ms.length;
const playable = ms.filter((m) => rank(m) >= STATUS.indexOf('playable')).length;
const logic = ms.filter((m) => rank(m) >= STATUS.indexOf('logic')).length;
const bots = ms.filter((m) => m.bot).length;
const dataLevels = ms.filter((m) => m.levels === 'data').length;
const bar = (n, t, w = 24) => {
  const full = t ? Math.round((w * n) / t) : 0;
  return '█'.repeat(full) + '░'.repeat(w - full);
};

const stageRows = STATUS.map((s) => `| ${s} | ${ms.filter((m) => m.status === s).length} |`);
const summary = [
  `**Playable: ${playable} / ${total}** \`${bar(playable, total)}\``,
  '',
  `Logic with tests or better: ${logic} / ${total} · Bot interface: ${bots} / ${total} · Data levels: ${dataLevels}`,
  '',
  '| Stage | Mechanics |',
  '|---|---|',
  ...stageRows,
].join('\n');

const families = [...new Set(ms.map((m) => m.family))];
const familyRows = families.map((f) => {
  const list = ms.filter((m) => m.family === f);
  const done = list.filter((m) => rank(m) >= STATUS.indexOf('playable')).length;
  return `| ${f} | ${list.length} | ${done} |`;
});
const sections = families.map((f) => {
  const rows = ms
    .filter((m) => m.family === f)
    .map((m) => `| ${m.id} | ${m.title ? `${m.name} (${m.title})` : m.name} | ${m.status} | ${m.levels || '-'} | ${m.bot ? 'yes' : '-'} | ${m.source} |`);
  return [`### ${f}`, '', '| ID | Mechanic | Status | Levels | Bot | Source |', '|---|---|---|---|---|---|', ...rows].join('\n');
});

const statusMd = [
  '# Status',
  '',
  '_Generated by `npm run status`. Do not edit by hand._',
  '',
  summary,
  '',
  '## By family',
  '',
  '| Family | Total | Playable or better |',
  '|---|---|---|',
  ...familyRows,
  '',
  '## All mechanics',
  '',
  sections.join('\n\n'),
  '',
].join('\n');

const BLOCK = /<!-- STATUS:START -->[\s\S]*?<!-- STATUS:END -->/;
const block = `<!-- STATUS:START -->\n${summary}\n\nFull table: [registry/STATUS.md](registry/STATUS.md)\n<!-- STATUS:END -->`;

const statusPath = path.join(ROOT, 'registry', 'STATUS.md');
const readmePath = path.join(ROOT, 'README.md');
const norm = (s) => s.replace(/\r\n/g, '\n');
const readme = norm(fs.readFileSync(readmePath, 'utf8'));
if (!BLOCK.test(readme)) {
  console.error('README.md is missing the STATUS:START / STATUS:END markers');
  process.exit(1);
}
const newReadme = readme.replace(BLOCK, () => block);
const oldStatus = fs.existsSync(statusPath) ? norm(fs.readFileSync(statusPath, 'utf8')) : '';

if (process.argv.includes('--check')) {
  if (oldStatus !== statusMd || readme !== newReadme) {
    console.error('STATUS.md or the README progress block is out of date. Run: npm run status');
    process.exit(1);
  }
  console.log('status ok');
} else {
  fs.writeFileSync(statusPath, statusMd);
  fs.writeFileSync(readmePath, newReadme);
  console.log(`status written: ${playable}/${total} playable`);
}
